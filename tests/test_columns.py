from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.schema import CreateTable

from jobmecloud.db.models import Job, RunJob


def ddl(model, dialect):
    return str(CreateTable(model.__table__).compile(dialect=dialect))


def test_postgres_primary_key_is_bigint_identity_with_a_cache_dsql_accepts():
    sql = ddl(Job, postgresql.dialect())
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 1)" in sql
    assert "SERIAL" not in sql


def test_dsql_only_accepts_cache_of_1_or_at_least_65536():
    from jobmecloud.db.columns import ID_CACHE
    assert ID_CACHE == 1 or ID_CACHE >= 65536


def test_postgres_foreign_keys_are_bigint():
    sql = ddl(RunJob, postgresql.dialect())
    assert "run_id BIGINT NOT NULL" in sql and "job_id BIGINT NOT NULL" in sql


def test_sqlite_primary_key_stays_plain_integer():
    sql = ddl(Job, sqlite.dialect())
    assert "id INTEGER NOT NULL" in sql and "PRIMARY KEY (id)" in sql
    assert "IDENTITY" not in sql
